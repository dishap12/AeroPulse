rows=[]
for year, body in raw.items():
    pieces=body.split('|')
    assert len(pieces)==(8 if year==2026 else 12)
    yearrows=[]
    for month, piece in enumerate(pieces,1):
        domestic,transborder,international=map(int,piece.split())
        row={"airport":"YOW","year":year,"month":month,"domestic":domestic,"transborder":transborder,"international":international,"total":domestic+transborder+international,"status":"preliminary" if year==2026 else "reported"}
        rows.append(row);yearrows.append(row)
    totals=tuple(sum(r[k] for r in yearrows) for k in ('domestic','transborder','international','total'))
    assert totals==expected[year],f'{year}: {totals} != {expected[year]}'
yyz=[]
